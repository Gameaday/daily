/* Compiles the knowledge layer (knowledge/*.json) into the puzzle
   stores the games actually load - and with --write, regenerates them.

   The layer is the hand-maintained source for entities and their
   relations; the compiled stores are generated artifacts, exactly like
   the bank files (see export-puzzles.mjs). CI runs this in verify mode,
   so editing a compiled store by hand fails the build.

   - thread is the first recipe: people + events compile to its nodes,
     relations compile to its edges, both in canonical id order, and the
     store's picks are regenerated by the shared offline walk
   - entity types no recipe consumes yet (places, artifacts, quotes)
     are defined in knowledge/SCHEMA.md; a file appears here when the
     first recipe needs it, and this tool fails loudly if one is missing

   Lint (always, before anything compiles):
   - ids unique across every present entity file (one namespace: the
     Benjamin / John Franklin near miss stays impossible forever)
   - every relation endpoint must be a known entity; no self relations,
     no duplicate pairs
   - reveal sentences are required strings; years are positive integers
     or absent (ancient relations carry no y at all)

   Default mode (what CI runs) never writes anything and exits 1 on
   drift. Run: node tools/build-knowledge.mjs         (verify)
        node tools/build-knowledge.mjs --write   (regenerate) */
import fs from 'node:fs';
import { threadWalk } from './thread-walk.mjs';

const WRITE = process.argv.includes('--write');
const LIST = JSON.parse(fs.readFileSync('games.json', 'utf8'));

let fails = 0;
const fail = msg => { console.error('FAIL ' + msg); fails++; };

const readLayer = name => {
  const p = 'knowledge/' + name + '.json';
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
};

const people = readLayer('people');
const events = readLayer('events');
const relations = readLayer('relations');

for (const entry of [['people', people], ['events', events], ['relations', relations]]){
  if (!Array.isArray(entry[1]))
    fail('knowledge/' + entry[0] + '.json: missing or not an array');
}

/* entities: one id namespace across every type */
const entities = [];
for (const arr of [people, events]){
  if (!Array.isArray(arr)) continue;
  for (const x of arr){
    if (!x || typeof x.id !== 'string' || typeof x.n !== 'string' || typeof x.d !== 'string')
      fail('knowledge: entity needs string id, n and d: ' + JSON.stringify(x));
    else entities.push(x);
  }
}
{
  const seen = new Set();
  for (const x of entities){
    if (seen.has(x.id)) fail('knowledge: duplicate entity id ' + x.id);
    seen.add(x.id);
  }
}

/* relations: typed, dated where honest */
const rels = Array.isArray(relations) ? relations : [];
{
  const ids = new Set(entities.map(x => x.id));
  const pairs = new Set();
  for (const r of rels){
    if (!r || typeof r.a !== 'string' || typeof r.b !== 'string' || typeof r.w !== 'string' || !r.w)
      fail('knowledge: relation needs string a, b and w: ' + JSON.stringify(r));
    else if (!ids.has(r.a)) fail('knowledge: relation references unknown entity ' + r.a);
    else if (!ids.has(r.b)) fail('knowledge: relation references unknown entity ' + r.b);
    else if (r.a === r.b) fail('knowledge: relation connects ' + r.a + ' to itself');
    else if (r.y !== undefined && (!Number.isInteger(r.y) || r.y <= 0))
      fail('knowledge: relation year must be a positive integer or absent (' + r.a + ' - ' + r.b + ')');
    else {
      const key = r.a < r.b ? r.a + ':' + r.b : r.b + ':' + r.a;
      if (pairs.has(key)) fail('knowledge: duplicate relation pair ' + r.a + ' - ' + r.b);
      pairs.add(key);
    }
  }
}

/* ---------------- recipe: thread ---------------- */
function compileThread(){
  const nodes = entities.map(x => ({ id: x.id, n: x.n, d: x.d }))
    .sort((p, q) => p.id < q.id ? -1 : p.id > q.id ? 1 : 0);
  const edges = rels
    .filter(r => r.a && r.b && r.w)
    .map(r => r.y === undefined ? { a: r.a, b: r.b, w: r.w } : { a: r.a, b: r.b, y: r.y, w: r.w })
    .sort((p, q) => p.a < q.a ? -1 : p.a > q.a ? 1 : p.b < q.b ? -1 : p.b > q.b ? 1 : 0);
  if (nodes.length < LIST.minThreadNodes)
    fail('knowledge: thread nodes below the minimum (' + nodes.length + ' < ' + LIST.minThreadNodes + ')');
  const bank = { nodes: nodes, edges: edges };
  const picks = threadWalk(bank, LIST.threadDays);
  return JSON.stringify({ bank: bank, picks: picks }, null, 2) + '\n';
}

function checkStore(game, text){
  const path = 'puzzles/' + game + '/puzzles.json';
  let actual = null;
  try { actual = fs.readFileSync(path, 'utf8'); }
  catch (e) { /* missing file */ }
  if (actual === text){
    console.log('ok  knowledge: ' + game + ' store matches the compiled layer');
    return;
  }
  if (WRITE){
    fs.writeFileSync(path, text);
    console.log('wrote ' + path);
    return;
  }
  fail('knowledge: ' + path + ' drifted from the compiled layer (run: node tools/build-knowledge.mjs --write)');
}

if (LIST.gated.thread) checkStore('thread', compileThread());

if (fails){
  console.error('');
  console.error(fails + ' check(s) failed' + (WRITE ? '' : ' (run: node tools/build-knowledge.mjs --write)'));
  process.exit(1);
}
console.log('');
console.log(WRITE ? 'stores recompiled from the knowledge layer'
                 : 'the knowledge layer compiles to the committed stores');
