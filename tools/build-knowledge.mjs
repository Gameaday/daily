/* Compiles the knowledge layer (knowledge/*.json) into the puzzle
   stores the games actually load - and with --write, regenerates them.

   The layer is the hand-maintained source for entities and their
   relations; the compiled stores are generated artifacts, exactly like
   the bank files (see export-puzzles.mjs). CI runs this in verify mode,
   so editing a compiled store by hand fails the build.

   - thread is a recipe over the whole layer: people plus the curated
     event list in puzzles/thread/recipe.json compile to its nodes,
     the relations whose endpoints it knows compile to its edges,
     both in canonical id order, and
     the store's picks are regenerated by the shared offline walk
   - timeline and rounds are recipes over events: the ordered recipe
     files carry only event ids, the topic label and the flavor line
     come from the shared stories, the canonical description, year
     and month-day come from the layer, and the rounds store compiles
     byte-identical to the hand-authored store it replaces
   - brunch is a recipe over places and presence: the curated
     moments in puzzles/brunch/recipe.json pick a city and a year, and
     the compiler seats three people whose spans cover that city-year
     plus one impostor, alive that year but documented elsewhere;
     the seating rotates with the year so a crowded table does not
     serve the same faces twice
   - museum and cipher are whole-file recipes over artifacts and
     quotes: the made things carry their aliases, five clues and the
     story the reveal tells, and the quotes name their speakers by
     person id and carry the year and the source when they are
     defensible. Both files compile to their stores in file order,
     the file order being the day rotation, and this tool fails
     loudly if a needed file is missing
   - bogus and well-actually are whole-file twist recipes: each
     telling keys itself to the entity it is about when the layer
     knows it, and marks its lie by segment position; the lies
     stay authored, and both files compile to their stores in
     file order, the file order being the day rotation

   - sift is a recipe over the whole namespace: the boards in
     knowledge/sift.json carry their titles and four categories of
     three tiles, every tile keys to an entity id (an as carries the
     tile's own spelling when the display differs), and the boards
     compile in file order, the file order being the day rotation

   - fermi is a whole-file recipe over facts: the commonly cited
     figures carry the question and the defense of the number, and
     each fact keys itself to the entity it is about when the layer
     knows it; the file compiles in file order, the file order being
     the day rotation

   - superlative is a recipe over people: every life the layer dates
     at both ends joins the pool in canonical id order, the pool cuts
     into groups of four, and each group serves the question its own
     numbers can settle alone, the longest life or the first or last
     birth; the three questions rotate by group and a group no
     question can decide never serves. When the numbers seat every
     life a superlative it tops, longest or shortest, the board also
     carries a bonus match: four chips, one per life, that the player
     assigns; the one life no dim tops takes the most-average chip

   Lint (always, before anything compiles):
   - ids unique across every present entity file (one namespace: the
     Benjamin / John Franklin near miss stays impossible forever)
   - the wider world and the animals join the one id namespace now:
     nothing compiles from them yet, but a colliding id fails the
     build the moment it lands
   - every relation endpoint must be a known entity; no self relations,
     no duplicate pairs, and a t, when present, comes from the shared
     relation vocabulary
   - reveal sentences are required strings; years are positive integers
     or absent (ancient relations carry no y at all)
   - optional entity fields are honest or absent: d and q are strings,
     y a positive integer, month 1-12 and day 1-31, a day never appears
     without its month, born and died are positive integers in order,
     and every presence span runs forward between a known person and a
     known place
   - presence spans stay inside their person's life dates, and a dated
     relation touches at least one living endpoint and never precedes
     the event it names
   - every story names a known event, and no story is told twice
   - artifacts carry their alias strings, five clue strings and a
     story, with no duplicate names and no alias that names another
     artifact
   - quotes carry a unique id outside the entity namespace, a known
     speaker, never the same text twice, and a year inside the life
     of the speaker
   - twist tellings carry an id outside the entity and quote
     namespaces, a lie position that points at a real segment, and
     a reveal; bogus tellings are titled uniquely, well-actually
     tellings name their answer among its accepted spellings, and
     neither file may cluster its lies into fewer than three
     positions
   - sift boards carry unique titles, four categories of three
     tiles, and every tile keys to a known entity; no tile id
     appears twice in one board

   Default mode (what CI runs) never writes anything and exits 1 on
   drift. Run: node tools/build-knowledge.mjs         (verify)
        node tools/build-knowledge.mjs --write   (regenerate) */
import fs from 'node:fs';
import { threadWalk, pickForDay } from './thread-walk.mjs';

const WRITE = process.argv.includes('--write');
const LIST = JSON.parse(fs.readFileSync('games.json', 'utf8'));

let fails = 0;
const fail = msg => { console.error('FAIL ' + msg); fails++; };

const readLayer = name => {
  const p = 'knowledge/' + name + '.json';
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
};

const readRecipe = game =>
  JSON.parse(fs.readFileSync('puzzles/' + game + '/recipe.json', 'utf8'));

const people = readLayer('people');
const events = readLayer('events');
const relations = readLayer('relations');
const places = readLayer('places');
const presence = readLayer('presence');
const stories = readLayer('stories');
const artifacts = readLayer('artifacts');
const quotes = readLayer('quotes');
const bogus = readLayer('bogus');
const wellActually = readLayer('well-actually');
const world = readLayer('world');
const animals = readLayer('animals');
const sift = readLayer('sift');
const facts = readLayer('facts');

for (const entry of [['people', people], ['events', events], ['places', places],
                       ['relations', relations], ['presence', presence],
                       ['stories', stories], ['artifacts', artifacts], ['quotes', quotes], ['bogus', bogus], ['well-actually', wellActually],
                       ['world', world], ['animals', animals], ['sift', sift], ['facts', facts]]){
  if (!Array.isArray(entry[1]))
    fail('knowledge/' + entry[0] + '.json: missing or not an array');
}

/* entities: one id namespace across every type */
const entities = [];
for (const arr of [people, events, places, artifacts, animals, world]){
  if (!Array.isArray(arr)) continue;
  for (const x of arr){
    if (!x || typeof x.id !== 'string' || typeof x.n !== 'string')
      fail('knowledge: entity needs string id and n: ' + JSON.stringify(x));
    else {
      if (x.d !== undefined && typeof x.d !== 'string')
        fail('knowledge: entity ' + x.id + ' field d must be a string');
      if (x.q !== undefined && typeof x.q !== 'string')
        fail('knowledge: entity ' + x.id + ' field q must be a string');
      if (x.y !== undefined && (!Number.isInteger(x.y) || x.y <= 0))
        fail('knowledge: entity ' + x.id + ' year must be a positive integer or absent');
      if (x.month !== undefined && (!Number.isInteger(x.month) || x.month < 1 || x.month > 12))
        fail('knowledge: entity ' + x.id + ' month must be an integer 1-12 or absent');
      if (x.day !== undefined && (!Number.isInteger(x.day) || x.day < 1 || x.day > 31))
        fail('knowledge: entity ' + x.id + ' day must be an integer 1-31 or absent');
      if (x.day !== undefined && x.month === undefined)
        fail('knowledge: entity ' + x.id + ' carries a day without a month');
      if (x.born !== undefined && (!Number.isInteger(x.born) || x.born <= 0))
        fail('knowledge: entity ' + x.id + ' born must be a positive integer or absent');
      if (x.died !== undefined && (!Number.isInteger(x.died) || x.died <= 0))
        fail('knowledge: entity ' + x.id + ' died must be a positive integer or absent');
      if (x.born !== undefined && x.died !== undefined && x.born > x.died)
        fail('knowledge: entity ' + x.id + ' is born after dying');
      entities.push(x);
    }
  }
}
{
  const seen = new Set();
  for (const x of entities){
    if (seen.has(x.id)) fail('knowledge: duplicate entity id ' + x.id);
    seen.add(x.id);
  }
}
const byId = {};
for (const x of entities) byId[x.id] = x;

/* artifacts: the made things museum hangs its clues on */
{
  const names = new Set();
  for (const x of (Array.isArray(artifacts) ? artifacts : [])){
    if (!x || typeof x.id !== 'string') continue;
    if (!Array.isArray(x.al) || !x.al.length || x.al.some(v => typeof v !== 'string' || !v))
      fail('knowledge: artifact ' + x.id + ' needs alias strings (al)');
    else if (!Array.isArray(x.c) || x.c.length !== 5 || x.c.some(v => typeof v !== 'string' || !v))
      fail('knowledge: artifact ' + x.id + ' needs five clue strings (c)');
    else if (typeof x.w !== 'string' || !x.w)
      fail('knowledge: artifact ' + x.id + ' needs a story (w)');
    else if (new Set(x.al).size !== x.al.length)
      fail('knowledge: artifact ' + x.id + ' has duplicate aliases');
    else if (names.has(x.n))
      fail('knowledge: artifact ' + x.id + ' duplicates the name ' + x.n);
    else if (artifacts.some(y => y !== x && typeof y.n === 'string' && x.al.includes(y.n)))
      fail('knowledge: artifact ' + x.id + ' lists an alias that names another artifact');
    else names.add(x.n);
  }
}

/* quotes: the sayings cipher hides, keyed to their speakers */
{
  const ids = new Set(entities.map(x => x.id));
  const seen = new Set();
  const peopleIds = new Set(Array.isArray(people) ? people.map(x => x.id) : []);
  const texts = new Set();
  for (const x of (Array.isArray(quotes) ? quotes : [])){
    if (!x || typeof x.id !== 'string') continue;
    if (seen.has(x.id)) fail('knowledge: quote id ' + x.id + ' appears twice');
    else if (ids.has(x.id)) fail('knowledge: quote id collides with an entity: ' + x.id);
    else if (!peopleIds.has(x.by)) fail('knowledge: quote names an unknown speaker: ' + x.by);
    else if (typeof x.q !== 'string' || !x.q) fail('knowledge: quote ' + x.id + ' needs text (q)');
    else if (texts.has(x.q)) fail('knowledge: quote ' + x.id + ' tells a quote twice');
    else if (x.y !== undefined && (!Number.isInteger(x.y) || x.y <= 0))
      fail('knowledge: quote ' + x.id + ' year must be a positive integer or absent');
    else if (x.via !== undefined && (typeof x.via !== 'string' || !x.via))
      fail('knowledge: quote ' + x.id + ' needs a via string or none');
    else if (x.provenance !== undefined && (typeof x.provenance !== 'string' || !x.provenance))
      fail('knowledge: quote ' + x.id + ' needs a provenance string or none');
    else {
      seen.add(x.id);
      texts.add(x.q);
      const speaker = byId[x.by];
      if (x.y !== undefined && speaker && speaker.born !== undefined && speaker.died !== undefined &&
          (x.y < speaker.born || x.y > speaker.died))
        fail('knowledge: quote ' + x.id + ' falls outside the life of its speaker');
    }
  }
}

/* twists: the lies stay authored, but keyed and marked */
{
  const ids = new Set(entities.map(x => x.id));
  const quoteIds = new Set((Array.isArray(quotes) ? quotes : [])
    .filter(q => q && typeof q.id === 'string').map(q => q.id));
  const taken = new Set();
  for (const [file, arr, isBogus] of [
      ['bogus', Array.isArray(bogus) ? bogus : [], true],
      ['well-actually', Array.isArray(wellActually) ? wellActually : [], false]]){
    const titles = new Set();
    const pairs = new Set();
    const lies = new Set();
    for (const x of arr){
      const where = 'knowledge/' + file + '.json';
      if (!x || typeof x.id !== 'string' || !x.id){
        fail(where + ': twist needs a string id');
        continue;
      }
      if (taken.has(x.id)) fail('knowledge: twist id ' + x.id + ' appears twice');
      else if (ids.has(x.id)) fail('knowledge: twist id collides with an entity: ' + x.id);
      else if (quoteIds.has(x.id)) fail('knowledge: twist id collides with a quote: ' + x.id);
      else taken.add(x.id);
      if (typeof x.t !== 'string' || !x.t) fail(where + ' twist ' + x.id + ' needs a title (t)');
      if (!Number.isInteger(x.l) || x.l < 0) fail(where + ' twist ' + x.id + ' needs a lie position (l)');
      if (!Array.isArray(x.s) || !x.s.length || x.s.some(v => typeof v !== 'string' || !v))
        fail(where + ' twist ' + x.id + ' needs segment strings (s)');
      else if (Number.isInteger(x.l) && x.l >= x.s.length)
        fail(where + ' twist ' + x.id + ' marks its lie outside the segments');
      if (typeof x.w !== 'string' || !x.w) fail(where + ' twist ' + x.id + ' needs a reveal (w)');
      if (x.about !== undefined && !ids.has(x.about))
        fail(where + ' twist ' + x.id + ' is about an unknown entity: ' + x.about);
      if (isBogus){
        if (x.s && x.s.length < 5)
          fail('knowledge: bogus telling ' + x.id + ' needs at least five segments');
        if (typeof x.t === 'string' && titles.has(x.t))
          fail('knowledge: bogus telling tells ' + x.t + ' twice');
        titles.add(x.t);
      } else {
        if (x.s && x.s.length < 4)
          fail('knowledge: well-actually telling ' + x.id + ' needs at least four segments');
        if (typeof x.c !== 'string' || !x.c)
          fail('knowledge: well-actually telling ' + x.id + ' needs the answer (c)');
        if (!Array.isArray(x.a) || !x.a.length || x.a.some(v => typeof v !== 'string' || !v))
          fail('knowledge: well-actually telling ' + x.id + ' needs accepted answers (a)');
        else if (typeof x.c === 'string' && !x.a.includes(x.c))
          fail('knowledge: well-actually telling ' + x.id + ' omits its own answer');
        else if (new Set(x.a).size !== x.a.length)
          fail('knowledge: well-actually telling ' + x.id + ' repeats an answer');
        if (typeof x.t === 'string' && typeof x.c === 'string'){
          const pair = x.t + ':' + x.c;
          if (pairs.has(pair)) fail('knowledge: well-actually answers ' + x.c + ' under ' + x.t + ' twice');
          pairs.add(pair);
        }
      }
      if (Number.isInteger(x.l)) lies.add(x.l);
    }
    if (arr.length && lies.size < 3)
      fail('knowledge: ' + file + ' clusters its lies in fewer than three positions');
  }
}
/* relations: typed, dated where honest */
const RELATION_TYPES = ['ally', 'colleague', 'correspondent', 'editor',
  'family', 'friend', 'housed-at', 'influence', 'kindred', 'lover',
  'member', 'opposed', 'participant', 'partnered', 'patron',
  'physician', 'resident', 'rival', 'site-of', 'successor',
  'teacher', 'translator'];
const rels = Array.isArray(relations) ? relations : [];
{
  const ids = new Set(entities.map(x => x.id));
  const pairs = new Set();
  for (const r of rels){
    if (!r || typeof r.a !== 'string' || typeof r.b !== 'string' || typeof r.w !== 'string' || !r.w)
      fail('knowledge: relation needs string a, b and w: ' + JSON.stringify(r));
    else if (!ids.has(r.a)) fail('knowledge: relation references unknown entity ' + r.a);
    else if (!ids.has(r.b)) fail('knowledge: relation references unknown entity ' + r.b);
    else if (r.a === r.b) fail('knowledge: relation connects ' + r.a + ' to itself');
    else if (r.t !== undefined && !RELATION_TYPES.includes(r.t))
      fail('knowledge: relation t is not in the shared vocabulary: ' + r.t + ' (' + r.a + ' - ' + r.b + ')');
    else if (r.y !== undefined && (!Number.isInteger(r.y) || r.y <= 0))
      fail('knowledge: relation year must be a positive integer or absent (' + r.a + ' - ' + r.b + ')');
    else {
      if (r.y !== undefined){
        const lives = [r.a, r.b].map(end => byId[end])
          .filter(ent => ent && ent.born !== undefined && ent.died !== undefined);
        if (lives.length && !lives.some(ent => r.y >= ent.born && r.y <= ent.died))
          fail('knowledge: relation year touches no living endpoint (' + r.a + ' - ' + r.b + ')');
        for (const end of [r.a, r.b]){
          const ent = byId[end];
          if (ent && ent.y !== undefined && r.y < ent.y)
            fail('knowledge: relation year precedes the event (' + r.a + ' - ' + r.b + ')');
        }
      }
      const key = r.a < r.b ? r.a + ':' + r.b : r.b + ':' + r.a;
      if (pairs.has(key)) fail('knowledge: duplicate relation pair ' + r.a + ' - ' + r.b);
      pairs.add(key);
    }
  }
}

/* presence spans: where people demonstrably were */
{
  const peopleIds = new Set(Array.isArray(people) ? people.map(x => x.id) : []);
  const placeIds = new Set(Array.isArray(places) ? places.map(x => x.id) : []);
  const rows = new Set();
  for (const s of (Array.isArray(presence) ? presence : [])){
    if (!s || typeof s.p !== 'string' || typeof s.place !== 'string' ||
        !Number.isInteger(s.from) || !Number.isInteger(s.to))
      fail('knowledge: presence needs string p and place and integer from and to: ' + JSON.stringify(s));
    else if (!peopleIds.has(s.p)) fail('knowledge: presence references unknown person ' + s.p);
    else if (!placeIds.has(s.place)) fail('knowledge: presence references unknown place ' + s.place);
    else if (s.from <= 0 || s.to < s.from)
      fail('knowledge: presence span must run forward (' + s.p + ' at ' + s.place + ')');
    else {
      const owner = byId[s.p];
      if (owner && owner.born !== undefined && s.from < owner.born)
        fail('knowledge: presence span starts before birth (' + s.p + ' at ' + s.place + ')');
      if (owner && owner.died !== undefined && s.to > owner.died)
        fail('knowledge: presence span runs past death (' + s.p + ' at ' + s.place + ')');
      const key = s.p + ':' + s.place + ':' + s.from + ':' + s.to;
      if (rows.has(key)) fail('knowledge: duplicate presence span ' + s.p + ' at ' + s.place);
      rows.add(key);
    }
  }
}

/* stories: the shared tellings the year games borrow */
const storiesById = {};
{
  const eventIds = new Set(Array.isArray(events) ? events.map(x => x.id) : []);
  for (const s of (Array.isArray(stories) ? stories : [])){
    if (!s || typeof s.id !== 'string' || typeof s.t !== 'string' || typeof s.w !== 'string')
      fail('knowledge: story needs string id, t and w: ' + JSON.stringify(s));
    else if (!eventIds.has(s.id)) fail('knowledge: story references unknown event ' + s.id);
    else if (storiesById[s.id]) fail('knowledge: duplicate story ' + s.id);
    else storiesById[s.id] = s;
  }
}

/* ---------------- recipe: thread ---------------- */
function compileThread(){
  const ids = readRecipe('thread');
  if (!Array.isArray(ids)){
    fail('thread recipe must be an array of event ids');
    return null;
  }
  const eventIds = new Set(Array.isArray(events) ? events.map(x => x.id) : []);
  const chosen = [];
  for (const id of ids){
    if (!eventIds.has(id)) fail('thread recipe references unknown event ' + id);
    else chosen.push(byId[id]);
  }
  const nodes = [];
  for (const x of (Array.isArray(people) ? people : []).concat(chosen)){
    if (x.d === undefined) fail('knowledge: thread node ' + x.id + ' needs a descriptor (d)');
    else nodes.push({ id: x.id, n: x.n, d: x.d });
  }
  nodes.sort((p, q) => p.id < q.id ? -1 : p.id > q.id ? 1 : 0);
  const nodeIds = new Set(nodes.map(x => x.id));
  const edges = rels
    .filter(r => r.a && r.b && r.w && nodeIds.has(r.a) && nodeIds.has(r.b))
    .map(r => r.y === undefined ? { a: r.a, b: r.b, w: r.w } : { a: r.a, b: r.b, y: r.y, w: r.w })
    .sort((p, q) => p.a < q.a ? -1 : p.a > q.a ? 1 : p.b < q.b ? -1 : p.b > q.b ? 1 : 0);
  if (nodes.length < LIST.minThreadNodes)
    fail('knowledge: thread nodes below the minimum (' + nodes.length + ' < ' + LIST.minThreadNodes + ')');
  const bank = { nodes: nodes, edges: edges };
  const picks = threadWalk(bank, LIST.threadDays);
  return JSON.stringify({ bank: bank, picks: picks }, null, 2) + '\n';
}

/* ---------------- recipes: timeline and rounds ---------------- */
function compileEventBank(game){
  const recipe = readRecipe(game);
  if (!Array.isArray(recipe) || recipe.some(x => typeof x !== 'string')){
    fail(game + ' recipe must be an array of event ids');
    return null;
  }
  const eventIds = new Set(Array.isArray(events) ? events.map(x => x.id) : []);
  const bank = [];
  for (const id of recipe){
    if (!eventIds.has(id)){
      fail(game + ' recipe references unknown event ' + id);
      continue;
    }
    const story = storiesById[id];
    if (!story){
      fail(game + ' recipe has no story for ' + id);
      continue;
    }
    const e = byId[id];
    if (typeof e.q !== 'string' || !Number.isInteger(e.y))
      fail(game + ' event ' + e.id + ' needs a description (q) and a year (y)');
    else bank.push({ t: story.t, q: e.q, y: e.y, w: story.w });
  }
  return bank;
}

function compileTimeline(){
  const bank = compileEventBank('timeline');
  if (!bank) return null;
  if (bank.length < LIST.minTimelineBank)
    fail('knowledge: timeline bank below the minimum (' + bank.length + ' < ' + LIST.minTimelineBank + ')');
  const picks = [];
  for (let day = 0; day < LIST.timelineDays; day++) picks.push(pickForDay(bank, day));
  return JSON.stringify({ bank: bank, picks: picks }, null, 2) + '\n';
}

function compileRounds(){
  const bank = compileEventBank('rounds');
  if (!bank) return null;
  if (bank.length < LIST.minBank)
    fail('knowledge: rounds bank below the minimum (' + bank.length + ' < ' + LIST.minBank + ')');
  return JSON.stringify(bank, null, 2) + '\n';
}

/* ---------------- recipe: brunch ---------------- */
function seatTable(placeId, y, folk, places, spans) {
    const placeNames = {};
    for (const pl of Array.isArray(places) ? places : [])placeNames[pl.id] = pl.n;
    if (!placeNames[placeId]) return null;
    const present = spans.filter((s)=>s.place === placeId && s.from <= y && s.to >= y).sort((p, q)=>p.to - p.from - (q.to - q.from) || (p.p < q.p ? -1 : 1));
    if (present.length < 3) return null;
    const rot = (y * 7 + placeId.length) % 251;
    const shift = rot % present.length;
    const trio = present.slice(shift).concat(present.slice(0, shift)).slice(0, 3);
    const away = [];
    for (const f of Array.isArray(folk) ? folk : []){
      if (!f || f.born === undefined || f.died === undefined || y < f.born || y > f.died) continue;
      if (present.some((s)=>s.p === f.id)) continue;
      const other = spans.filter((s)=>s.p === f.id && s.place !== placeId && s.from <= y && s.to >= y).sort((p, q)=>p.to - p.from - (q.to - q.from))[0];
      if (!other) continue;
      const tie = spans.some((s)=>s.p === f.id && s.place === placeId) ? 1 : 0;
      away.push({
        id: f.id,
        n: f.n,
        tie: tie,
        span: other
      });
    }
    if (!away.length) return null;
    away.sort((p, q)=>q.tie - p.tie || (p.id < q.id ? -1 : 1));
    const hi = away.filter((x)=>x.tie === away[0].tie);
    const imp = hi[rot % hi.length];
    const names = [];
    for (const s of trio){
      const f = folk.find((x)=>x.id === s.p);
      if (!f) return null;
      names.push(f.n);
    }
    names.push(imp.n);
    if (new Set(names).size !== 4) return null;
    const a = (y * 3 + placeId.length) % 4;
    const opts = [];
    let j = 0;
    for(let i = 0; i < 4; i++)opts[i] = i === a ? imp.n : names[j++];
    const q = placeNames[placeId] + ', ' + y + '. Three of these four were in the city that year. Who missed the table?';
    const w = 'In ' + placeNames[placeId] + ' then: ' + trio.map((s)=>{
      const f = folk.find((x)=>x.id === s.p);
      return f.n + ' (' + s.from + '-' + s.to + ')';
    }).join(', ') + '. ' + imp.n + ' was in ' + placeNames[imp.span.place] + ' (' + imp.span.from + '-' + imp.span.to + ').';
    return {
      t: placeNames[placeId],
      y: y,
      q: q,
      opts: opts,
      a: a,
      w: w
    };
  }

function compileBrunch(){
  const recipe = readRecipe('brunch');
  if (!Array.isArray(recipe)){
    fail('brunch recipe must be an array of { id, y } moments');
    return null;
  }
  const placeIds = new Set(Array.isArray(places) ? places.map(x => x.id) : []);
  const rows = new Set();
  const bank = [];
  for (const m of recipe){
    if (!m || !placeIds.has(m.id) || !Number.isInteger(m.y) || m.y <= 0){
      fail('brunch recipe moment needs a known place id and a positive year: ' + JSON.stringify(m));
      continue;
    }
    const key = m.id + ':' + m.y;
    if (rows.has(key)){ fail('brunch recipe has a duplicate moment: ' + key); continue; }
    rows.add(key);
    const entry = seatTable(m.id, m.y, people, places, Array.isArray(presence) ? presence : []);
    if (!entry) fail('brunch moment cannot be seated (three present, one elsewhere): ' + key);
    else bank.push(entry);
  }
  if (bank.length < LIST.minBank)
    fail('knowledge: brunch bank below the minimum (' + bank.length + ' < ' + LIST.minBank + ')');
  return JSON.stringify(bank, null, 2) + '\n';
}

