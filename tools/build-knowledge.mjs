/* Compiles the knowledge layer (knowledge/*.json) into the puzzle
   stores the games actually load - and with --write, regenerates them.

   The layer is the hand-maintained source for entities and their
   relations; the compiled stores are generated artifacts, exactly like
   the bank files (see export-puzzles.mjs). CI runs this in verify mode,
   so editing a compiled store by hand fails the build.

   - thread is a recipe over the whole layer: people plus the curated
     event list in puzzles/thread/recipe.json compile to its nodes,
     relations compile to its edges, both in canonical id order, and
     the store's picks are regenerated by the shared offline walk
   - timeline and rounds are recipes over events: the ordered recipe
     files carry each game's own copy (the topic label and the flavor
     line), the canonical description, year and month-day come from
     the layer, and the stores compile byte-identical to the
     hand-authored stores they replace
   - places and presence spans are seeded but no recipe consumes
     them yet (brunch will be the first); artifacts and quotes are
     defined in knowledge/SCHEMA.md, and this tool fails loudly if a
     needed file is missing

   Lint (always, before anything compiles):
   - ids unique across every present entity file (one namespace: the
     Benjamin / John Franklin near miss stays impossible forever)
   - every relation endpoint must be a known entity; no self relations,
     no duplicate pairs
   - reveal sentences are required strings; years are positive integers
     or absent (ancient relations carry no y at all)
   - optional entity fields are honest or absent: d and q are strings,
     y a positive integer, month 1-12 and day 1-31, a day never appears
     without its month, born and died are positive integers in order,
     and every presence span runs forward between a known person and a
     known place

   Default mode (what CI runs) never writes anything and exits 1 on
   drift. Run: node tools/build-knowledge.mjs         (verify)
        node tools/build-knowledge.mjs --write   (regenerate) */
import fs from 'node:fs';
import { threadWalk, pickForDay } from './thread-walk.mjs';

const WRITE = process.argv.includes('--write');
const LIST = JSON.parse(fs.readFileSync('games.json', 'utf8'));

let fails = 0;
const fail = msg => { console.error('FAIL ' + msg); fails++; };

const readLayer = name => {
  const p = 'knowledge/' + name + '.json';
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
};

const readRecipe = game =>
  JSON.parse(fs.readFileSync('puzzles/' + game + '/recipe.json', 'utf8'));

const people = readLayer('people');
const events = readLayer('events');
const relations = readLayer('relations');
const places = readLayer('places');
const presence = readLayer('presence');

for (const entry of [['people', people], ['events', events], ['places', places],
                       ['relations', relations], ['presence', presence]]){
  if (!Array.isArray(entry[1]))
    fail('knowledge/' + entry[0] + '.json: missing or not an array');
}

/* entities: one id namespace across every type */
const entities = [];
for (const arr of [people, events, places]){
  if (!Array.isArray(arr)) continue;
  for (const x of arr){
    if (!x || typeof x.id !== 'string' || typeof x.n !== 'string')
      fail('knowledge: entity needs string id and n: ' + JSON.stringify(x));
    else {
      if (x.d !== undefined && typeof x.d !== 'string')
        fail('knowledge: entity ' + x.id + ' field d must be a string');
      if (x.q !== undefined && typeof x.q !== 'string')
        fail('knowledge: entity ' + x.id + ' field q must be a string');
      if (x.y !== undefined && (!Number.isInteger(x.y) || x.y <= 0))
        fail('knowledge: entity ' + x.id + ' year must be a positive integer or absent');
      if (x.month !== undefined && (!Number.isInteger(x.month) || x.month < 1 || x.month > 12))
        fail('knowledge: entity ' + x.id + ' month must be an integer 1-12 or absent');
      if (x.day !== undefined && (!Number.isInteger(x.day) || x.day < 1 || x.day > 31))
        fail('knowledge: entity ' + x.id + ' day must be an integer 1-31 or absent');
      if (x.day !== undefined && x.month === undefined)
        fail('knowledge: entity ' + x.id + ' carries a day without a month');
      if (x.born !== undefined && (!Number.isInteger(x.born) || x.born <= 0))
        fail('knowledge: entity ' + x.id + ' born must be a positive integer or absent');
      if (x.died !== undefined && (!Number.isInteger(x.died) || x.died <= 0))
        fail('knowledge: entity ' + x.id + ' died must be a positive integer or absent');
      if (x.born !== undefined && x.died !== undefined && x.born > x.died)
        fail('knowledge: entity ' + x.id + ' is born after dying');
      entities.push(x);
    }
  }
}
{
  const seen = new Set();
  for (const x of entities){
    if (seen.has(x.id)) fail('knowledge: duplicate entity id ' + x.id);
    seen.add(x.id);
  }
}
const byId = {};
for (const x of entities) byId[x.id] = x;

/* relations: typed, dated where honest */
const rels = Array.isArray(relations) ? relations : [];
{
  const ids = new Set(entities.map(x => x.id));
  const pairs = new Set();
  for (const r of rels){
    if (!r || typeof r.a !== 'string' || typeof r.b !== 'string' || typeof r.w !== 'string' || !r.w)
      fail('knowledge: relation needs string a, b and w: ' + JSON.stringify(r));
    else if (!ids.has(r.a)) fail('knowledge: relation references unknown entity ' + r.a);
    else if (!ids.has(r.b)) fail('knowledge: relation references unknown entity ' + r.b);
    else if (r.a === r.b) fail('knowledge: relation connects ' + r.a + ' to itself');
    else if (r.y !== undefined && (!Number.isInteger(r.y) || r.y <= 0))
      fail('knowledge: relation year must be a positive integer or absent (' + r.a + ' - ' + r.b + ')');
    else {
      const key = r.a < r.b ? r.a + ':' + r.b : r.b + ':' + r.a;
      if (pairs.has(key)) fail('knowledge: duplicate relation pair ' + r.a + ' - ' + r.b);
      pairs.add(key);
    }
  }
}

/* presence spans: where people demonstrably were */
{
  const peopleIds = new Set(Array.isArray(people) ? people.map(x => x.id) : []);
  const placeIds = new Set(Array.isArray(places) ? places.map(x => x.id) : []);
  const rows = new Set();
  for (const s of (Array.isArray(presence) ? presence : [])){
    if (!s || typeof s.p !== 'string' || typeof s.place !== 'string' ||
        !Number.isInteger(s.from) || !Number.isInteger(s.to))
      fail('knowledge: presence needs string p and place and integer from and to: ' + JSON.stringify(s));
    else if (!peopleIds.has(s.p)) fail('knowledge: presence references unknown person ' + s.p);
    else if (!placeIds.has(s.place)) fail('knowledge: presence references unknown place ' + s.place);
    else if (s.from <= 0 || s.to < s.from)
      fail('knowledge: presence span must run forward (' + s.p + ' at ' + s.place + ')');
    else {
      const key = s.p + ':' + s.place + ':' + s.from + ':' + s.to;
      if (rows.has(key)) fail('knowledge: duplicate presence span ' + s.p + ' at ' + s.place);
      rows.add(key);
    }
  }
}

/* ---------------- recipe: thread ---------------- */
function compileThread(){
  const ids = readRecipe('thread');
  if (!Array.isArray(ids)){
    fail('thread recipe must be an array of event ids');
    return null;
  }
  const eventIds = new Set(Array.isArray(events) ? events.map(x => x.id) : []);
  const chosen = [];
  for (const id of ids){
    if (!eventIds.has(id)) fail('thread recipe references unknown event ' + id);
    else chosen.push(byId[id]);
  }
  const nodes = [];
  for (const x of (Array.isArray(people) ? people : []).concat(chosen)){
    if (x.d === undefined) fail('knowledge: thread node ' + x.id + ' needs a descriptor (d)');
    else nodes.push({ id: x.id, n: x.n, d: x.d });
  }
  nodes.sort((p, q) => p.id < q.id ? -1 : p.id > q.id ? 1 : 0);
  const edges = rels
    .filter(r => r.a && r.b && r.w)
    .map(r => r.y === undefined ? { a: r.a, b: r.b, w: r.w } : { a: r.a, b: r.b, y: r.y, w: r.w })
    .sort((p, q) => p.a < q.a ? -1 : p.a > q.a ? 1 : p.b < q.b ? -1 : p.b > q.b ? 1 : 0);
  if (nodes.length < LIST.minThreadNodes)
    fail('knowledge: thread nodes below the minimum (' + nodes.length + ' < ' + LIST.minThreadNodes + ')');
  const bank = { nodes: nodes, edges: edges };
  const picks = threadWalk(bank, LIST.threadDays);
  return JSON.stringify({ bank: bank, picks: picks }, null, 2) + '\n';
}

/* ---------------- recipes: timeline and rounds ---------------- */
function compileEventBank(game){
  const recipe = readRecipe(game);
  if (!Array.isArray(recipe)){
    fail(game + ' recipe must be an array of { id, t, w } entries');
    return null;
  }
  const eventIds = new Set(Array.isArray(events) ? events.map(x => x.id) : []);
  const bank = [];
  for (const r of recipe){
    if (!r || !eventIds.has(r.id)){
      fail(game + ' recipe references unknown event ' + (r && r.id));
      continue;
    }
    if (typeof r.t !== 'string' || typeof r.w !== 'string'){
      fail(game + ' recipe entry needs string t and w: ' + JSON.stringify(r));
      continue;
    }
    const e = byId[r.id];
    if (typeof e.q !== 'string' || !Number.isInteger(e.y))
      fail(game + ' event ' + e.id + ' needs a description (q) and a year (y)');
    else bank.push({ t: r.t, q: e.q, y: e.y, w: r.w });
  }
  return bank;
}

function compileTimeline(){
  const bank = compileEventBank('timeline');
  if (!bank) return null;
  if (bank.length < LIST.minTimelineBank)
    fail('knowledge: timeline bank below the minimum (' + bank.length + ' < ' + LIST.minTimelineBank + ')');
  const picks = [];
  for (let day = 0; day < LIST.timelineDays; day++) picks.push(pickForDay(bank, day));
  return JSON.stringify({ bank: bank, picks: picks }, null, 2) + '\n';
}

function compileRounds(){
  const bank = compileEventBank('rounds');
  if (!bank) return null;
  if (bank.length < LIST.minBank)
    fail('knowledge: rounds bank below the minimum (' + bank.length + ' < ' + LIST.minBank + ')');
  return JSON.stringify(bank, null, 2) + '\n';
}

function checkStore(game, text){
  const path = 'puzzles/' + game + '/puzzles.json';
  let actual = null;
  try { actual = fs.readFileSync(path, 'utf8'); }
  catch (e) { /* missing file */ }
  if (actual === text){
    console.log('ok  knowledge: ' + game + ' store matches the compiled layer');
    return;
  }
  if (WRITE){
    fs.writeFileSync(path, text);
    console.log('wrote ' + path);
    return;
  }
  fail('knowledge: ' + path + ' drifted from the compiled layer (run: node tools/build-knowledge.mjs --write)');
}

if (LIST.gated.thread) checkStore('thread', compileThread());
if (LIST.gated.timeline) checkStore('timeline', compileTimeline());
if (LIST.gated.rounds) checkStore('rounds', compileRounds());

if (fails){
  console.error('');
  console.error(fails + ' check(s) failed' + (WRITE ? '' : ' (run: node tools/build-knowledge.mjs --write)'));
  process.exit(1);
}
console.log('');
console.log(WRITE ? 'stores recompiled from the knowledge layer'
                 : 'the knowledge layer compiles to the committed stores');
