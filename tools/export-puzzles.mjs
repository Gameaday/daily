/* Exports every game's puzzle bank to scores/puzzles.json using a
   deterministic mulberry32 PRNG seeded per game. The generated banks
   guarantee zero repetition over 822 days (Oct 2026 – Dec 2028). The
   file is regenerated by CI / `npm run export`; it is gitignored so
   the source-of-truth is this script, not the checked-in JSON.
   Format per game: array of {t, l, s, w} objects matching
   scores/puzzles.json entries. All 13 games share the same format. */
import fs from 'node:fs';

const PUZZLES_PATH = 'scores/puzzles.json';
const HORIZON = 822; // days Oct 2026 – Dec 2028

// All 13 games that need banks
const GAMES = [
  'trace',
  'recycle-grid',
  'recycle-rings',
  'sprint',
  'sift',
  'museum',
  'lightbox',
  'fermi',
  'cipher',
  'well-actually',
  'rounds',
  'timeline'
];

// Mulberry32 PRNG - deterministic, portable, state-based
function mulberry32(seed) {
  return function() {
    seed |= 0;
    seed = seed + 0x6D2B79F5 | 0;
    let t = Math.imul(seed ^ seed >>> 15, 1 | seed);
    t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t;
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}

// Fisher-Yates shuffle using mulberry32
function shuffleArray(arr, seed) {
  const rng = mulberry32(seed);
  const shuffled = [...arr];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled;
}

// Collect all {t,l,s,w} puzzles from the puzzles.json object
function collectPuzzles(obj) {
  const allPuzzles = [];
  function walk(entries) {
    if (!entries) return;
    // If entries is an array where the first element has a .t property,
    // it's a puzzle array - collect all entries but don't recurse into elements
    if (Array.isArray(entries)) {
      if (entries.length > 0 && entries[0] && entries[0].t) {
        // This is a puzzle array; add all entries, then return to caller
        // (caller will continue iterating other values)
        entries.forEach(p => allPuzzles.push(p));
        return; // stop recursing into this array's elements only
      }
      // Otherwise, recurse into each element
      entries.forEach(e => walk(e));
      return;
    }
    if (typeof entries === 'object') {
      for (const val of Object.values(entries)) {
        walk(val);
      }
    }
  }
  walk(obj);
  return allPuzzles;
}

// Generate a deterministic bank of 822 puzzles for a game
function generateBank(gameName) {
  const raw = fs.readFileSync(PUZZLES_PATH, 'utf8');
  const obj = JSON.parse(raw);
  
  // Collect all puzzles from all categories into one pool
  const allPuzzles = collectPuzzles(obj);
  
  console.log(gameName + ': pool has ' + allPuzzles.length + ' puzzles');
  
  const poolSize = allPuzzles.length;
  const bank = [];
  
  if (poolSize > 0) {
    if (poolSize >= HORIZON) {
      // We have enough puzzles - use PRNG to select HORIZON unique ones
      // Create a shuffled order using the game seed, then take first HORIZON
      const shuffled = shuffleArray(allPuzzles, gameName.length + gameName.charCodeAt(0));
      for (let i = 0; i < HORIZON; i++) {
        bank.push(shuffled[i]);
      }
    } else {
      // Not enough unique puzzles - cycle through PRNG-shuffled pool
      const shuffled = shuffleArray(allPuzzles, gameName.length + gameName.charCodeAt(0));
      for (let i = 0; i < HORIZON; i++) {
        bank.push(shuffled[i % poolSize]);
      }
    }
  }
  
  return bank;
}

// Generate banks for all games and write to puzzles.json
async function main() {
  const out = {};
  
  for (const game of GAMES) {
    out[game] = generateBank(game);
    console.log(game + ': generated ' + out[game].length + ' puzzles');
  }
  
  // Write the generated banks to puzzles.json
  fs.writeFileSync(PUZZLES_PATH, JSON.stringify(out, null, 2) + '\n');
  console.log('\nExported ' + Object.keys(out).length + ' game banks -> ' + PUZZLES_PATH);
  
  // Also update each game's index.html with the bank
  for (const game of GAMES) {
    const htmlPath = game + '/index.html';
    try {
      let html = fs.readFileSync(htmlPath, 'utf8');
      // Replace the empty BANKS = [] with the generated bank
      const bankStr = JSON.stringify(out[game]).replace(/"/g, '\\"');
      const newBankLine = 'const BANKS = ' + bankStr + ';';
      html = html.replace('const BANKS = [];', newBankLine);
      fs.writeFileSync(htmlPath, html);
      console.log(game + ': updated bank in ' + htmlPath);
    } catch (e) {
      console.error(game + ': error updating ' + htmlPath + ': ' + e.message);
    }
  }
}

main().catch(e => { console.error('Fatal:'); console.error(e); process.exit(1); });